                {auditProgressStep >= 1 ? <CheckCircle2 size={15} color="#10B981" /> : <div style={{ width: '12px', height: '12px', borderRadius: '50%', border: '2px solid #CBD5E1' }} />}
                <span>1. Resolving Host &amp; DNS Records</span>
